import { copyFileSync, existsSync, mkdirSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { allCharacters, allWords } from '../../src/data/index.ts'
import { hsk5Words } from '../../src/data/hsk5/words.ts'

/*
 * Copies the audio-cmn recordings that match the app's words and characters
 * into public/audio, plus the syllable recordings used as a fallback for
 * words without a whole-word recording. Writes the lists of available files
 * for the app.
 *
 *   git clone --depth 1 --filter=blob:none --sparse \
 *     https://github.com/hugolpz/audio-cmn.git /tmp/audio-cmn
 *   git -C /tmp/audio-cmn sparse-checkout set 24k-abr/hsk 24k-abr/syllabs
 *   npm run audio:import -- /tmp/audio-cmn/24k-abr
 *
 * Source: https://github.com/hugolpz/audio-cmn (CC BY-SA, Chen Wang and
 * Yue Tan). See public/audio/ATTRIBUTION.txt.
 */

const sourceRoot = process.argv[2]
if (!sourceRoot) {
  console.error('Usage: npm run audio:import -- <path to audio-cmn/24k-abr>')
  process.exit(1)
}

const root = join(dirname(fileURLToPath(import.meta.url)), '../..')
const wordSource = join(sourceRoot, 'hsk')
const syllableSource = join(sourceRoot, 'syllabs')
const destination = join(root, 'public/audio')
const syllableDestination = join(destination, 'syllables')
mkdirSync(syllableDestination, { recursive: true })

/**
 * audio-cmn has one file per hanzi. For these, the file's reading is
 * ambiguous, so the app uses the syllable fallback instead.
 */
const HOMOGRAPHS = new Set(['长', '得', '还', '只'])

const wanted = new Set([
  ...allWords.map((word) => word.hanzi),
  ...hsk5Words.map((word) => word.hanzi),
  ...allCharacters.map((character) => character.hanzi),
])

const missing: string[] = []
let copied = 0
for (const hanzi of wanted) {
  if (HOMOGRAPHS.has(hanzi)) continue
  const file = `cmn-${hanzi}.mp3`
  const from = join(wordSource, file)
  if (!existsSync(from)) {
    missing.push(hanzi)
    continue
  }
  copyFileSync(from, join(destination, file))
  copied += 1
}

let syllableCount = 0
for (const file of readdirSync(syllableSource)) {
  if (!file.startsWith('cmn-') || !file.endsWith('.mp3')) continue
  copyFileSync(join(syllableSource, file), join(syllableDestination, file))
  syllableCount += 1
}

const available = readdirSync(destination)
  .filter((file) => file.startsWith('cmn-') && file.endsWith('.mp3'))
  .map((file) => file.slice('cmn-'.length, -'.mp3'.length))
  .sort()
const syllables = readdirSync(syllableDestination)
  .filter((file) => file.startsWith('cmn-') && file.endsWith('.mp3'))
  .map((file) => file.slice('cmn-'.length, -'.mp3'.length))
  .sort()

function lines(items: readonly string[]): string[] {
  const result: string[] = []
  for (let index = 0; index < items.length; index += 20) {
    result.push(`  ${items.slice(index, index + 20).map((item) => `'${item}'`).join(', ')},`)
  }
  return result
}

writeFileSync(
  join(root, 'src/data/audio.ts'),
  [
    '// Generated by scripts/audio/import.ts. Do not edit by hand.',
    '// Pronunciation audio: audio-cmn (https://github.com/hugolpz/audio-cmn),',
    '// 24k-abr/hsk and 24k-abr/syllabs, CC BY-SA. See public/audio/ATTRIBUTION.txt.',
    'export const AUDIO_HANZI: ReadonlySet<string> = new Set([',
    ...lines(available),
    '])',
    '',
    '/** Syllable recordings, used when a word has no whole-word file. */',
    'export const AUDIO_SYLLABLES: ReadonlySet<string> = new Set([',
    ...lines(syllables),
    '])',
    '',
  ].join('\n'),
)

console.log(`Copied ${copied} word/character recordings and ${syllableCount} syllables.`)
console.log(`Available hanzi: ${available.length}. Missing: ${missing.length}.`)
if (missing.length > 0) console.log(`Missing sample: ${missing.slice(0, 20).join(' ')}`)
