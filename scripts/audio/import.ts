import { copyFileSync, existsSync, mkdirSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { allCharacters, allWords } from '../../src/data/index.ts'
import { hsk5Words } from '../../src/data/hsk5/words.ts'

/*
 * Copies the audio-cmn recordings that match the app's words and characters
 * into public/audio, and writes the list of available hanzi for the app.
 *
 *   git clone --depth 1 --filter=blob:none --sparse \
 *     https://github.com/hugolpz/audio-cmn.git /tmp/audio-cmn
 *   git -C /tmp/audio-cmn sparse-checkout set 24k-abr/hsk
 *   npm run audio:import -- /tmp/audio-cmn/24k-abr/hsk
 *
 * Source: https://github.com/hugolpz/audio-cmn (CC BY-SA, Chen Wang and
 * Yue Tan). See public/audio/ATTRIBUTION.txt.
 */

const source = process.argv[2]
if (!source) {
  console.error('Usage: npm run audio:import -- <path to audio-cmn/24k-abr/hsk>')
  process.exit(1)
}

const root = join(dirname(fileURLToPath(import.meta.url)), '../..')
const destination = join(root, 'public/audio')
mkdirSync(destination, { recursive: true })

/**
 * audio-cmn has one file per hanzi. For these, the file's reading is
 * ambiguous, so the app doesn't offer audio for them.
 */
const HOMOGRAPHS = new Set(['长', '得', '还', '只'])

const wanted = new Set([
  ...allWords.map((word) => word.hanzi),
  ...hsk5Words.map((word) => word.hanzi),
  ...allCharacters.map((character) => character.hanzi),
])

const missing: string[] = []
let copied = 0
for (const hanzi of wanted) {
  if (HOMOGRAPHS.has(hanzi)) continue
  const file = `cmn-${hanzi}.mp3`
  const from = join(source, file)
  if (!existsSync(from)) {
    missing.push(hanzi)
    continue
  }
  copyFileSync(from, join(destination, file))
  copied += 1
}

const available = readdirSync(destination)
  .filter((file) => file.startsWith('cmn-') && file.endsWith('.mp3'))
  .map((file) => file.slice('cmn-'.length, -'.mp3'.length))
  .sort()

const lines: string[] = []
for (let index = 0; index < available.length; index += 20) {
  lines.push(`  ${available.slice(index, index + 20).map((hanzi) => `'${hanzi}'`).join(', ')},`)
}
writeFileSync(
  join(root, 'src/data/audio.ts'),
  [
    '// Generated by scripts/audio/import.ts. Do not edit by hand.',
    '// Pronunciation audio: audio-cmn (https://github.com/hugolpz/audio-cmn),',
    '// 24k-abr/hsk, CC BY-SA. See public/audio/ATTRIBUTION.txt.',
    'export const AUDIO_HANZI: ReadonlySet<string> = new Set([',
    ...lines,
    '])',
    '',
  ].join('\n'),
)

console.log(`Copied ${copied} audio files to public/audio.`)
console.log(`Available hanzi: ${available.length}. Missing: ${missing.length}.`)
if (missing.length > 0) console.log(`Missing sample: ${missing.slice(0, 20).join(' ')}`)
